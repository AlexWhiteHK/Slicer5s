F35 = {}
for k, v in _T.items():
    rows = v.split('|')
    a = np.array([[c == '#' for c in r] for r in rows], dtype=bool)
    F35[k] = a


def tiny_mask(s, spacing=1):
    cols = []
    for i, ch in enumerate(s.upper()):
        g = F35.get(ch, F35[' '])
        cols.append(g)
        if i != len(s) - 1:
            cols.append(np.zeros((5, spacing), dtype=bool))
    return np.concatenate(cols, axis=1) if cols else np.zeros((5, 1), bool)


# ---------------------------------------------------------------- Unifont (CJK)
_UNI = ImageFont.truetype('/usr/share/fonts/opentype/unifont/unifont_jp.otf', 16)
_uni_cache = {}


def uni_mask(s):
    """Unifont bitmap for (mostly CJK) text, 16px tall."""
    if s in _uni_cache:
        return _uni_cache[s]
    w = int(_UNI.getlength(s)) + 2
    im = Image.new('1', (w, 16), 0)
    d = ImageDraw.Draw(im)
    d.fontmode = '1'
    d.text((0, 0), s, font=_UNI, fill=1)
    a = np.array(im, dtype=bool)
    xs = np.where(a.any(axis=0))[0]
    if len(xs):
        a = a[:, :xs[-1] + 1]
    _uni_cache[s] = a
    return a
