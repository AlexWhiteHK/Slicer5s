CELL_H = 9          # 7 cap rows + 2 descender rows
_TABULAR = set('0123456789')


def _parse(src):
    rows = src.split('\n')
    w = max(len(r) for r in rows)
    a = np.zeros((CELL_H, w), dtype=bool)
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            if c == '#':
                a[y, x] = True
    return a


F57 = {k: _parse(v) for k, v in _G.items()}


def glyph(ch):
    if ch in F57:
        return F57[ch]
    alias = {'’': "'", '‘': "'", '“': '"', '”': '"', '…': '.', '−': '-'}
    if ch in alias:
        return F57[alias[ch]]
    return F57['?']


def text_mask(s, spacing=1, bold=False):
    """Render a string in the 5x7 font to a bool mask (height CELL_H)."""
    cols = []
    for i, ch in enumerate(s):
        g = glyph(ch)
        if bold:
            g2 = np.zeros((g.shape[0], g.shape[1] + 1), dtype=bool)
            g2[:, :-1] |= g
            g2[:, 1:] |= g
            g = g2
        cols.append(g)
        if i != len(s) - 1:
            cols.append(np.zeros((CELL_H, spacing), dtype=bool))
    if not cols:
        return np.zeros((CELL_H, 1), dtype=bool)
    return np.concatenate(cols, axis=1)


def text_width(s, spacing=1, bold=False):
    return text_mask(s, spacing, bold).shape[1]


